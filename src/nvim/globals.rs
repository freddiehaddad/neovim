#[repr(transparent)]
pub struct GlobalState<T>(std::cell::UnsafeCell<T>);

unsafe impl<T> Sync for GlobalState<T> {}

impl<T> GlobalState<T> {
    #[inline]
    pub const fn new(val: T) -> Self {
        Self(std::cell::UnsafeCell::new(val))
    }

    #[inline]
    pub const fn as_ptr(&self) -> *mut T {
        self.0.get()
    }
}

